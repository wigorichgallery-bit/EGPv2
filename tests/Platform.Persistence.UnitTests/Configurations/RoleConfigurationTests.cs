using Microsoft.EntityFrameworkCore.Metadata;
using Platform.Identity.Domain.Aggregates;
using Platform.Identity.Domain.ValueObjects;
using Platform.Persistence.Configurations;

namespace Platform.Persistence.UnitTests.Configurations;

/// <summary>
/// Contains unit tests for the
/// <see cref="RoleConfiguration"/> class.
///
/// Responsibility:
/// - Verify role table mapping.
/// - Verify role primary key configuration.
/// - Verify role scalar property configuration.
/// - Verify role name unique index configuration.
/// - Verify role scope value conversion.
/// - Verify permission owned collection mapping.
/// - Verify permission foreign key configuration.
/// - Verify permission composite key configuration.
/// - Verify permission backing field configuration.
/// - Verify ignored domain event mapping.
/// - Verify null builder validation.
///
/// Testing Strategy:
/// - Exercise the public Configure method.
/// - Inspect the resulting EF Core model metadata.
/// - Do not access private configuration methods directly.
/// - Do not require a physical database.
/// </summary>
public sealed class RoleConfigurationTests
{
    /// <summary>
    /// Creates an EF Core model containing the
    /// <see cref="RoleConfiguration"/> mapping.
    ///
    /// The model is created entirely in memory so that
    /// persistence metadata can be verified without
    /// connecting to a database.
    /// </summary>
    /// <returns>
    /// The configured mutable EF Core model.
    /// </returns>
    private static IMutableModel CreateModel()
    {
        var modelBuilder = new ModelBuilder();

        modelBuilder.ApplyConfiguration(
            new RoleConfiguration());

        return modelBuilder.Model;
    }

    /// <summary>
    /// Verifies that Configure throws an
    /// <see cref="ArgumentNullException"/> when
    /// the entity builder is null.
    /// </summary>
    [Fact]
    public void Configure_Should_ThrowArgumentNullException_When_BuilderIsNull()
    {
        // Arrange
        var sut = new RoleConfiguration();

        // Act
        Action act = () => sut.Configure(null!);

        // Assert
        act.Should()
            .Throw<ArgumentNullException>();
    }

    /// <summary>
    /// Verifies that Role is mapped to the
    /// IdentityRoles table.
    /// </summary>
    [Fact]
    public void Configure_Should_MapRoleToIdentityRolesTable()
    {
        // Arrange
        var model = CreateModel();

        // Act
        var entityType = model.FindEntityType(
            typeof(Role));

        // Assert
        entityType.Should()
            .NotBeNull();

        entityType!
            .GetTableName()
            .Should()
            .Be("IdentityRoles");
    }

    /// <summary>
    /// Verifies that Role.Id is configured as the
    /// primary key and that its value is never
    /// generated by the database.
    /// </summary>
    [Fact]
    public void Configure_Should_ConfigureIdAsNonGeneratedPrimaryKey()
    {
        // Arrange
        var model = CreateModel();

        var entityType = model.FindEntityType(
            typeof(Role));

        entityType.Should()
            .NotBeNull();

        // Act
        var primaryKey = entityType!
            .FindPrimaryKey();

        var idProperty = entityType.FindProperty(
            nameof(Role.Id));

        // Assert
        primaryKey.Should()
            .NotBeNull();

        primaryKey!
            .Properties
            .Should()
            .ContainSingle();

        primaryKey.Properties[0]
            .Name
            .Should()
            .Be(nameof(Role.Id));

        idProperty.Should()
            .NotBeNull();

        idProperty!
            .ValueGenerated
            .Should()
            .Be(ValueGenerated.Never);
    }

    /// <summary>
    /// Verifies that Role.Name is required
    /// and has a maximum length of 200 characters.
    /// </summary>
    [Fact]
    public void Configure_Should_ConfigureNameAsRequiredWithMaximumLength()
    {
        // Arrange
        var model = CreateModel();

        var entityType = model.FindEntityType(
            typeof(Role));

        entityType.Should()
            .NotBeNull();

        // Act
        var property = entityType!
            .FindProperty(nameof(Role.Name));

        // Assert
        property.Should()
            .NotBeNull();

        property!
            .IsNullable
            .Should()
            .BeFalse();

        property
            .GetMaxLength()
            .Should()
            .Be(200);
    }

    /// <summary>
    /// Verifies that Role.Name has a unique
    /// database index.
    /// </summary>
    [Fact]
    public void Configure_Should_CreateUniqueIndexForName()
    {
        // Arrange
        var model = CreateModel();

        var entityType = model.FindEntityType(
            typeof(Role));

        entityType.Should()
            .NotBeNull();

        // Act
        var indexes = entityType!
            .GetIndexes()
            .Where(index =>
                index.Properties.Count == 1
                && index.Properties[0].Name
                    == nameof(Role.Name))
            .ToList();

        // Assert
        indexes.Should()
            .ContainSingle();

        indexes[0]
            .IsUnique
            .Should()
            .BeTrue();
    }

