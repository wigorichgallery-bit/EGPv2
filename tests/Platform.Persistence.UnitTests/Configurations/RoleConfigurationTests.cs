    /// <summary>
    /// Verifies that Role.Scope uses a value converter,
    /// is persisted as a string, uses the Scope column,
    /// has a maximum length of 100 characters,
    /// and is required.
    /// </summary>
    [Fact]
    public void Configure_Should_ConfigureRoleScopeConversion()
    {
        // Arrange
        var model = CreateModel();

        var entityType = model.FindEntityType(
            typeof(Role));

        entityType.Should()
            .NotBeNull();

        // Act
        var property = entityType!
            .FindProperty(nameof(Role.Scope));

        // Assert
        property.Should()
            .NotBeNull();

        var converter = property!
            .GetValueConverter();

        converter.Should()
            .NotBeNull();

        converter!
            .ModelClrType
            .Should()
            .Be(typeof(RoleScope));

        converter
            .ProviderClrType
            .Should()
            .Be(typeof(string));

        property
            .GetColumnName()
            .Should()
            .Be("Scope");

        property
            .GetMaxLength()
            .Should()
            .Be(100);

        property
            .IsNullable
            .Should()
            .BeFalse();
    }

    /// <summary>
    /// Verifies that the configured RoleScope converter
    /// converts a RoleScope domain value object into
    /// its string persistence representation.
    /// </summary>
    [Fact]
    public void Configure_Should_ConvertRoleScopeToString()
    {
        // Arrange
        var model = CreateModel();

        var entityType = model.FindEntityType(
            typeof(Role));

        entityType.Should()
            .NotBeNull();

        var property = entityType!
            .FindProperty(nameof(Role.Scope));

        property.Should()
            .NotBeNull();

        var converter = property!
            .GetValueConverter();

        converter.Should()
            .NotBeNull();

        var scope = RoleScope.Global;

        // Act
        var converted =
            converter!
                .ConvertToProviderExpression
                .Compile()
                .DynamicInvoke(scope);

        // Assert
        converted.Should()
            .Be("GLOBAL");
    }

    /// <summary>
    /// Verifies that the configured RoleScope converter
    /// converts a persisted string into a RoleScope
    /// domain value object.
    /// </summary>
    [Fact]
    public void Configure_Should_ConvertStringToRoleScope()
    {
        // Arrange
        var model = CreateModel();

        var entityType = model.FindEntityType(
            typeof(Role));

        entityType.Should()
            .NotBeNull();

        var property = entityType!
            .FindProperty(nameof(Role.Scope));

        property.Should()
            .NotBeNull();

        var converter = property!
            .GetValueConverter();

        converter.Should()
            .NotBeNull();

        // Act
        var converted =
            converter!
                .ConvertFromProviderExpression
                .Compile()
                .DynamicInvoke("GLOBAL");

        // Assert
        converted.Should()
            .BeOfType<RoleScope>();

        ((RoleScope)converted!)
            .Value
            .Should()
            .Be("GLOBAL");
    }

