    /// <summary>
    /// Verifies that Configure produces the expected
    /// complete persistence metadata for the Role aggregate.
    /// </summary>
    [Fact]
    public void Configure_Should_ConfigureCompleteRolePersistenceModel()
    {
        // Arrange
        var model = CreateModel();

        // Act
        var roleEntityType = model.FindEntityType(
            typeof(Role));

        roleEntityType.Should()
            .NotBeNull();

        var permissionNavigation =
            roleEntityType!
                .FindNavigation(
                    nameof(Role.PermissionIds));

        // Assert
        roleEntityType
            .GetTableName()
            .Should()
            .Be("IdentityRoles");

        roleEntityType
            .FindPrimaryKey()!
            .Properties
            .Select(property => property.Name)
            .Should()
            .Equal(nameof(Role.Id));

        roleEntityType
            .FindProperty(nameof(Role.Name))!
            .GetMaxLength()
            .Should()
            .Be(200);

        roleEntityType
            .FindProperty(nameof(Role.Name))!
            .IsNullable
            .Should()
            .BeFalse();

        roleEntityType
            .FindProperty(nameof(Role.Scope))!
            .GetMaxLength()
            .Should()
            .Be(100);

        roleEntityType
            .FindProperty(nameof(Role.Scope))!
            .GetValueConverter()
            .Should()
            .NotBeNull();

        permissionNavigation.Should()
            .NotBeNull();

        permissionNavigation!
            .TargetEntityType
            .GetTableName()
            .Should()
            .Be("IdentityRolePermissions");

        permissionNavigation
            .TargetEntityType
            .FindPrimaryKey()!
            .Properties
            .Select(property => property.Name)
            .Should()
            .Equal(
                "RoleId",
                "Value");

        roleEntityType
            .FindProperty(
                nameof(Role.DomainEvents))
            .Should()
            .BeNull();
    }
