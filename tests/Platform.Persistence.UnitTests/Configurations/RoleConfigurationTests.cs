    /// <summary>
    /// Verifies that the permission owned entity
    /// contains a RoleId property and uses it as
    /// the foreign key to Role.
    /// </summary>
    [Fact]
    public void Configure_Should_ConfigurePermissionForeignKey()
    {
        // Arrange
        var model = CreateModel();

        var roleEntityType = model.FindEntityType(
            typeof(Role));

        roleEntityType.Should()
            .NotBeNull();

        var navigation = roleEntityType!
            .FindNavigation(
                nameof(Role.PermissionIds));

        navigation.Should()
            .NotBeNull();

        var ownedEntityType = navigation!
            .TargetEntityType;

        // Act
        var roleIdProperty = ownedEntityType
            .FindProperty("RoleId");

        var foreignKeys = ownedEntityType
            .GetForeignKeys()
            .Where(foreignKey =>
                foreignKey.Properties
                    .Any(property =>
                        property.Name == "RoleId"))
            .ToList();

        // Assert
        roleIdProperty.Should()
            .NotBeNull();

        foreignKeys.Should()
            .ContainSingle();

        foreignKeys[0]
            .PrincipalEntityType
            .ClrType
            .Should()
            .Be(typeof(Role));
    }

